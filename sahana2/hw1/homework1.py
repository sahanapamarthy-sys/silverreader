#Variables and Data Types 

a = 10 
print(a)
print(type(a)) #a is an integer, a whole number with no decimals

b = 1.5
print(b)
print(type(b)) #b is a float, a number with a decimal 

c = 3j 
print(c)
print(type(c)) #c is an imaginary number 

d = "hello" 
print(d)
print(type(d)) #d is a string 

e  = [1,2,3] 
print(e) 
print(type(e)) #
